let age = 10

console.log(message)
console.log(age)

// deklarasi variable secara multirows
let nama = 'hello',
umur = 21

console.log(nama)
console.log(umur)

nama = 'aloha'

console.log(nama)

let studentName = 'ujang'
nama = studentName // nama = ujang
studentName = nama // studentName = ujang

console.log(nama)
console.log(studentName)

